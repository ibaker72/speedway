import { dealerConfig } from "@/dealer.config";

/**
 * Canonical production origin. Every canonical URL, sitemap entry, and
 * structured-data URL is built from this so they never disagree.
 * Production serves www.speedwaymotorsllc.com (the apex redirects to it).
 */
export const SITE_URL = (process.env.NEXT_PUBLIC_SITE_URL || dealerConfig.website).replace(/\/+$/, "");

/** Build an absolute URL on the canonical origin from a site-relative path. */
export function absoluteUrl(path = "/"): string {
  if (/^https?:\/\//i.test(path)) return path;
  const normalized = path.startsWith("/") ? path : `/${path}`;
  return normalized === "/" ? `${SITE_URL}/` : `${SITE_URL}${normalized}`;
}

/** Stable @id for the dealership entity so other schema nodes can reference it. */
export const ORGANIZATION_ID = `${SITE_URL}/#organization`;

/** Default share image generated by app/opengraph-image.tsx. */
export const DEFAULT_OG_IMAGE = {
  url: `${SITE_URL}/opengraph-image`,
  width: 1200,
  height: 630,
  alt: `${dealerConfig.name} — Quality Used Cars in Paterson, NJ`,
};
